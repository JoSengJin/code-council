import type { TopicKind } from './types.js';

const scopeRules = `제안 전에 다음 순서를 따르고, 각 단계의 결과를 초안 앞부분에 짧게 적어라.
1. 관련 파일 확인: 주제가 언급한 경로와 설계 대상에 직접 관련된 진입점·호출자·데이터 흐름·설정 파일을 읽는다. 탐색은 핵심 파일 10개 안팎으로 제한하고 node_modules·dist·.next·lock 파일은 읽지 마라. 찾지 못한 것은 더 뒤지지 말고 "미확인"으로 표시하라. 프로젝트 밖의 로컬 경로가 언급되거나 설계 대상과 연결된 것으로 보이면 읽기 전용으로 함께 확인한다.
2. 경계 확인: 먼저 설계 대상의 종류(구조, 데이터, 알고리즘, 인터페이스, 성능 등)를 정하고, 그 대상의 동작과 해석을 가르는 경계만 확인한다. 대상이 바뀔 때 영향받는 소유 단위(모듈·프로세스·배포 단위 등), 호출자와 데이터 흐름, 입력·성능·호환성 제약 중 주제에 해당하는 것만 고른다. 주제와 무관한 경계 분석은 요구하지 마라.
3. 설계 대상 명시: 요청의 설계 대상과 범위를 밝힌다. 두 해석 이상이 가능하면 하나로 조용히 좁히지 말고, 해석마다 근거(요청 문구, 확인한 파일), 전제, 영향받는 범위를 나눠 설명하라. 선택 기준과 필요한 확인 질문을 제시하고, 사용자가 확정하지 않은 요구는 "미결정"으로 표시하라. 한 해석을 확정된 요구처럼 먼저 실행·상세화하지 말고, 해석별 설계는 같은 비중의 대안으로 제시하라. 확인하지 못한 경계는 "미확인"으로 표시하라.
4. 외부 원문 비교: 제공된 원문이 있으면 3에서 명시한 설계 대상과 같은 층위의 근거를 비교한다. 원문이 없으면 주제가 언급한 오픈소스·라이브러리를 답하기 전에 웹 검색으로 확인하고 확인한 URL을 적어라. 확인하지 못한 부분만 알고 있는 구조로 비교하되 "추정(기억 기반, 미검증)"으로 표시하라. 원문이 없다는 이유로 비교를 생략하지 마라.
5. 제안: 위에서 확인한 범위에 대해서만 제안한다. 한 해석만 다뤘다면 다른 해석은 미해결로 남기고, 전체 재설계가 끝났다고 결론 내리지 마라.`;

const evidenceRules = '확인한 사실은 로컬 파일·외부 원문·추정으로 구분하라. 원문을 직접 확인해 비교했다면 원문 링크와 커밋을 제시하라. 확인하지 못한 외부 내용은 추정으로 표시하고 확인된 사실처럼 단정하지 마라. 로컬 파일은 마크다운 링크가 아니라 백틱 안의 `전체경로:줄번호`로 인용하고, 실제로 열어 확인한 줄만 적어라. 줄을 확인하지 못했으면 줄번호 없이 경로만 적어라. 링크는 http(s) 외부 원문에만 사용하라. 코드는 수정하지 마라.';

const analysisRules = `질문에 직접 답하는 글만 쓴다. 파일을 읽은 과정, 확인 단계, 경계 분석은 서술하지 말고 결론과 근거만 적어라.
1. 구성: 질문이 요구한 항목(예: 장점, 제약, 고민거리, 비교, 권고)이 있으면 그 이름을 그대로 소제목으로 쓰고, 없으면 핵심 결론·근거·한계로 나눠라. 질문이 "핵심만"을 요구하면 항목당 2~3줄로 줄여라.
2. 해석: 질문이 둘 이상으로 읽히면 가장 개연성 높은 해석을 기본으로 정하고 이유를 한 줄로 밝혀라. 다른 해석은 어떤 조건이면 그쪽으로 가야 하는지만 짧게 붙이고 같은 비중으로 나열하지 마라. 사용자가 확정하지 않은 전제는 "가정"으로 표시하라.
3. 근거: 저장소가 지정되었으면 관련 파일을 핵심 10개 안팎만 읽고(node_modules·dist·.next·lock 제외) 주장과 직접 관련된 줄만 인용하라. 질문이 참고하라고 한 외부 오픈소스·라이브러리·문서는 답하기 전에 웹 검색으로 확인하고 URL을 적어라. 확인하지 못한 부분은 "추정(기억 기반, 미검증)"으로 표시하라.
4. 적용: 참고 대상에서 가져올 구체 요소를 항목으로 꼽고, 각각 우리 상황의 어디에 어떻게 적용되며 무엇이 달라지는지까지 연결하라. 일반론으로 끝내지 마라. 질문에 참고 대상이 없으면 이 항목은 생략한다.
5. 끝에, 확인하지 못해 결론에 영향을 주는 사항만 한두 줄로 적어라.`;

export function analysisConclusionPrompt(topic: string, hasProject: boolean, rounds: unknown): string {
  return `원래 질문: ${topic}
아래 토론을 바탕으로 질문에 직접 답하는 최종 결론을 작성하라. 질문하지 않은 구현 계획·파일별 변경·롤백 절차·검증 명령은 쓰지 마라.
구성: 질문이 요구한 항목(예: 장점, 제약, 고민거리, 비교, 권고)을 그대로 소제목으로 쓰고, 없으면 핵심 결론·근거·한계·적용 권고로 나눠라. 비교를 요구했으면 주제에 해당하는 비교 축만 골라 대조하라. 질문이 "핵심만"을 요구하면 항목당 2~3줄로 줄여라.
확인한 사실과 추정은 항목 끝에 짧게 구분하고, 미확인 사항은 마지막에 한두 줄로 모아라. 토론 과정(누가 무엇을 주장했는지)은 언급하지 마라.${hasProject ? ' 저장소에서 확인한 파일은 백틱 안의 `경로`로 인용하라.' : ''}
토론: ${JSON.stringify(rounds)}`;
}

export function firstDraftPrompt(topic: string, projectPath: string | undefined, references: string, kind: TopicKind = 'implementation'): string {
  const analysis = kind === 'analysis';
  const scope = projectPath
    ? `${analysis ? '저장소의 관련 파일을 근거로 답한다.' : '저장소의 관련 파일과 호출 경로를 근거로 설계한다.'}
${analysis ? analysisRules : scopeRules}`
    : analysis
      ? `프로젝트가 지정되지 않았다. 저장소 검증을 주장하지 마라.
${analysisRules}`
      : '프로젝트가 지정되지 않았다. 주제에 근거해 설계를 제안하고 저장소 검증을 주장하지 마라. 설계 대상이 모호하면 해석별 가정을 밝히고 각각 구조를 설명하라.';
  const purpose = analysis ? '위 주제가 묻는 내용에 직접 답하는 것이 목적이다.' : '위 주제가 묻는 내용(비교 대상, 얻는 장점, 보완할 점 등)에 직접 답하는 것이 목적이다. 아래 절차는 근거를 정리하는 용도이며 답을 대체하지 않는다.';
  return `개발 주제: ${topic}
${purpose}
${scope}
${evidenceRules}
${references}`;
}
